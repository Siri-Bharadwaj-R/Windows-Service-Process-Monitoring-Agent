"""
Digital signature verification section for the
Windows Service & Process Monitoring Agent PDF report.
"""


def build_digital_signature_results(
    results: list[dict[str, object]],
    findings: list[dict[str, str]],
    unique_paths: int,
) -> dict[str, object]:
    """
    Prepare digital signature verification information
    for the security assessment report.

    Args:
        results:
            Signature verification results generated by
            SignatureVerifier.

        findings:
            Security findings generated by SignatureVerifier.

        unique_paths:
            Number of unique executable paths verified.

    Returns:
        Dictionary containing signature statistics,
        unsigned executables, other signature states,
        and security findings.
    """

    valid_count = sum(
        result.get("status") == "Valid"
        for result in results
    )

    unsigned_count = sum(
        result.get("status") == "NotSigned"
        for result in results
    )

    other_count = len(results) - (
        valid_count + unsigned_count
    )

    unsigned_executables: list[dict[str, str]] = []
    displayed_paths: set[str] = set()

    for result in results:

        if result.get("status") != "NotSigned":
            continue

        path = str(
            result.get("path") or "Unknown"
        )

        normalized_path = path.lower()

        if normalized_path in displayed_paths:
            continue

        displayed_paths.add(normalized_path)

        unsigned_executables.append(
            {
                "process_name": str(
                    result.get("process_name")
                    or "Unknown"
                ),
                "path": path,
                "publisher": str(
                    result.get("publisher")
                    or "Unknown"
                ),
                "status": str(
                    result.get("status")
                    or "Unknown"
                ),
            }
        )

    other_states: list[dict[str, str]] = []
    displayed_paths.clear()

    for result in results:

        status = str(
            result.get("status")
            or "Unknown"
        )

        if status in {
            "Valid",
            "NotSigned",
        }:
            continue

        path = str(
            result.get("path") or "Unknown"
        )

        normalized_path = path.lower()

        if normalized_path in displayed_paths:
            continue

        displayed_paths.add(normalized_path)

        other_states.append(
            {
                "process_name": str(
                    result.get("process_name")
                    or "Unknown"
                ),
                "path": path,
                "publisher": str(
                    result.get("publisher")
                    or "Unknown"
                ),
                "status": status,
            }
        )

    return {
        "executables_checked": len(results),
        "unique_paths": unique_paths,
        "valid_signatures": valid_count,
        "unsigned": unsigned_count,
        "other_status": other_count,
        "unsigned_executables": unsigned_executables,
        "other_states": other_states,
        "findings": findings.copy(),
    }